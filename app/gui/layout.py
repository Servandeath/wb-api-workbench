"""
Общие константы вёрстки для GUI-секций.

Раньше каждый раздел придумывал отступы/ширины полей на глаз — из-за
этого одинаковые панели в разных разделах выглядели по-разному: разные
отступы, разная ширина полей, подписи не выровнены в одну колонку между
соседними панелями (например "Marketplace:" длиннее "Name:", и из-за
этого колонка с полями ввода в разных панелях начиналась в разных
местах). Один набор констант на всё приложение — так разделы выглядят
как части одной системы (как в МойСклад/ВБ), а не как разные экраны,
слепленные в разное время.
"""

# Скругление углов у панелей — единое для всех CTkFrame-карточек.
PANEL_CORNER_RADIUS = 12

# Внешний отступ контента секции от края окна.
CONTENT_PADX = 30

# Отступ между двумя панелями, когда они стоят рядом в одну строку.
PANEL_GAP = 10

# Внутренние отступы вокруг пары "подпись + поле" внутри панели.
FIELD_PADX = 20
FIELD_PADY = 15

# Фиксированная ширина подписи. Без неё колонка с полями ввода "плавает"
# между панелями с подписями разной длины — на глаз выглядит как будто
# формы не выровнены друг с другом.
LABEL_WIDTH = 160

# Стандартная ширина однострочных полей ввода/дропдаунов.
ENTRY_WIDTH = 240
# Широкое поле — для длинных значений (JSON body, путь запроса, токен).
ENTRY_WIDTH_WIDE = 320

TITLE_FONT_SIZE = 28
SECTION_FONT_SIZE = 18
BODY_FONT_SIZE = 16
LABEL_FONT_SIZE = 13
GROUP_TITLE_FONT_SIZE = 14


def build_group_header(parent, text: str, columnspan: int = 2) -> None:
    """
    Заголовок под-блока внутри панели — как title= у ttk.LabelFrame в
    wb-barcode-gui (там формы группируются в подписанные рамки "Текст",
    "Штрихкод" и т.д., а не свалены в одну панель без подписи). CTk не
    умеет рамку со врезанной подписью в бордюре, поэтому имитируем:
    жирный заголовок первой строкой панели, поля — под ним начиная со
    следующего row. Без этого несколько полей в одной панели выглядят
    как случайный набор, а не как осмысленный блок — особенно заметно,
    когда в панели мало полей и вокруг остаётся пустое место.
    """
    import customtkinter as ctk

    header = ctk.CTkLabel(
        parent,
        text=text,
        font=ctk.CTkFont(size=GROUP_TITLE_FONT_SIZE, weight="bold"),
        anchor="w",
    )
    header.grid(row=0, column=0, columnspan=columnspan, padx=FIELD_PADX, pady=(15, 5), sticky="w")
